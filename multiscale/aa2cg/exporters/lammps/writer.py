"""LAMMPS exporter scaffold for Multiscale CGSystem.

This exporter intentionally focuses on a LAMMPS data file (`system.data`)
and a minimal input skeleton (`in.cg`) from an existing CGSystem.  It does not
generate pair, bond, angle, IBI/IMC, or table-potential parameters.  Force-field coefficients are intentionally omitted and must be supplied from the selected parameter set.
"""
from __future__ import annotations

from dataclasses import dataclass
import csv
import json
from pathlib import Path
from typing import Any

from multiscale.core.cg_system import CGAngle, CGBead, CGBond, CGSystem


@dataclass(frozen=True)
class LammpsExportReport:
    outdir: str
    files: dict[str, str]
    counts: dict[str, Any]
    checks: dict[str, bool | None]

    @property
    def ok(self) -> bool:
        return all(value is not False for value in self.checks.values())

    def to_dict(self) -> dict[str, Any]:
        return {
            "outdir": self.outdir,
            "files": self.files,
            "counts": self.counts,
            "checks": self.checks,
            "ok": self.ok,
        }


def _length_to_angstrom(value: float, unit: str | None) -> float:
    normalized = (unit or "angstrom").lower()
    if normalized in {"angstrom", "angstroms", "a", "å"}:
        return float(value)
    if normalized in {"nm", "nanometer", "nanometers"}:
        return float(value) * 10.0
    raise ValueError(f"Unsupported length unit for LAMMPS export: {unit!r}")


def _box_to_angstrom(system: CGSystem) -> tuple[float, float, float]:
    if not system.box:
        return (0.0, 0.0, 0.0)
    return tuple(_length_to_angstrom(float(v), system.box_unit) for v in system.box)  # type: ignore[return-value]


def _position_to_angstrom(system: CGSystem, bead: CGBead) -> tuple[float, float, float]:
    if bead.position is None:
        return (0.0, 0.0, 0.0)
    return tuple(_length_to_angstrom(float(v), system.coordinate_unit) for v in bead.position)  # type: ignore[return-value]


def _stable_type_names(values: list[str | None], fallback_prefix: str) -> list[str]:
    names = sorted({str(v) for v in values if v})
    if not names:
        names = [f"{fallback_prefix}1"]
    return names


def _type_id_map(names: list[str]) -> dict[str, int]:
    return {name: idx for idx, name in enumerate(names, start=1)}


def _bead_type_name(bead: CGBead) -> str:
    return str(bead.bead_type or bead.name or f"B{bead.index}")


def _bond_type_name(bond: CGBond) -> str:
    return str(bond.bond_type or "bond1")


def _angle_type_name(angle: CGAngle) -> str:
    return str(angle.angle_type or "angle1")


def _mean_mass_for_type(system: CGSystem, bead_type: str) -> float:
    masses = [float(b.mass) for b in system.beads if _bead_type_name(b) == bead_type and b.mass is not None]
    if not masses:
        return 1.0
    return sum(masses) / len(masses)


def _comment_safe(value: str) -> str:
    return str(value).replace("\n", " ").replace("#", "_")


def _lammps_type_maps(system: CGSystem) -> dict[str, Any]:
    bead_types = _stable_type_names([_bead_type_name(b) for b in system.beads], "atom")
    bond_types = _stable_type_names([_bond_type_name(b) for b in system.bonds], "bond") if system.bonds else []
    angle_types = _stable_type_names([_angle_type_name(a) for a in system.angles], "angle") if system.angles else []
    return {
        "atom_type_ids": _type_id_map(bead_types),
        "bond_type_ids": _type_id_map(bond_types),
        "angle_type_ids": _type_id_map(angle_types),
        "atom_types": bead_types,
        "bond_types": bond_types,
        "angle_types": angle_types,
    }


def render_lammps_data(system: CGSystem) -> str:
    """Render an clean data file readable by OVITO and LAMMPS.

    Keep `system.data` machine-readable: no explanatory rows inside Masses,
    Atoms, Bonds, or Angles, and no trailing bead-name comments on data rows.
    Human-readable type/name metadata is written separately by
    :func:`write_lammps_files` into JSON/CSV sidecar files.
    """
    maps = _lammps_type_maps(system)
    bead_types = maps["atom_types"]
    bond_types = maps["bond_types"]
    angle_types = maps["angle_types"]
    bead_type_ids = maps["atom_type_ids"]
    bond_type_ids = maps["bond_type_ids"]
    angle_type_ids = maps["angle_type_ids"]
    lx, ly, lz = _box_to_angstrom(system)

    lines: list[str] = [
        f"# Generated by Multiscale LAMMPS scaffold: {system.name}",
        "# Structural scaffold only; force-field coefficients are not generated.",
        "# Data sections are written in standard LAMMPS syntax and can be inspected with OVITO.",
        "",
        f"{len(system.beads)} atoms",
        f"{len(system.bonds)} bonds",
        f"{len(system.angles)} angles",
        "",
        f"{len(bead_types)} atom types",
        f"{len(bond_types)} bond types",
        f"{len(angle_types)} angle types",
        "",
        f"{0.0: .6f} {lx: .6f} xlo xhi",
        f"{0.0: .6f} {ly: .6f} ylo yhi",
        f"{0.0: .6f} {lz: .6f} zlo zhi",
        "",
        "Masses",
        "",
    ]
    for name in bead_types:
        lines.append(f"{bead_type_ids[name]:6d} {_mean_mass_for_type(system, name):14.6f}")

    lines.extend(["", "Atoms # full", ""])
    for bead in sorted(system.beads, key=lambda b: b.index):
        x, y, z = _position_to_angstrom(system, bead)
        type_name = _bead_type_name(bead)
        lines.append(
            f"{bead.index:8d} {int(bead.molecule_index or 1):6d} {bead_type_ids[type_name]:6d} "
            f"{float(bead.charge or 0.0):14.8f} {x:14.6f} {y:14.6f} {z:14.6f}"
        )

    if system.bonds:
        lines.extend(["", "Bonds", ""])
        for idx, bond in enumerate(sorted(system.bonds, key=lambda b: (b.molecule_index or 0, b.i, b.j)), start=1):
            type_name = _bond_type_name(bond)
            lines.append(f"{idx:8d} {bond_type_ids[type_name]:6d} {bond.i:8d} {bond.j:8d}")

    if system.angles:
        lines.extend(["", "Angles", ""])
        for idx, angle in enumerate(sorted(system.angles, key=lambda a: (a.molecule_index or 0, a.i, a.j, a.k)), start=1):
            type_name = _angle_type_name(angle)
            lines.append(f"{idx:8d} {angle_type_ids[type_name]:6d} {angle.i:8d} {angle.j:8d} {angle.k:8d}")

    return "\n".join(lines) + "\n"


def lammps_type_map(system: CGSystem) -> dict[str, Any]:
    maps = _lammps_type_maps(system)
    return {
        "schema": "multiscale.lammps_type_map.v0",
        "system_name": system.name,
        "atom_style": "full",
        "units": "real",
        "length_unit": "angstrom",
        "atom_types": [
            {
                "id": maps["atom_type_ids"][name],
                "name": name,
                "mass": _mean_mass_for_type(system, name),
            }
            for name in maps["atom_types"]
        ],
        "bond_types": [
            {"id": maps["bond_type_ids"][name], "name": name}
            for name in maps["bond_types"]
        ],
        "angle_types": [
            {"id": maps["angle_type_ids"][name], "name": name}
            for name in maps["angle_types"]
        ],
    }


def write_lammps_bead_map_csv(system: CGSystem, path: str | Path) -> None:
    maps = _lammps_type_maps(system)
    atom_type_ids = maps["atom_type_ids"]
    with Path(path).open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow([
            "atom_id",
            "molecule_id",
            "molecule_bead_index",
            "atom_type_id",
            "atom_type_name",
            "bead_name",
            "mass",
            "charge",
            "x_angstrom",
            "y_angstrom",
            "z_angstrom",
        ])
        for bead in sorted(system.beads, key=lambda b: b.index):
            type_name = _bead_type_name(bead)
            x, y, z = _position_to_angstrom(system, bead)
            writer.writerow([
                bead.index,
                int(bead.molecule_index or 1),
                bead.molecule_bead_index or "",
                atom_type_ids[type_name],
                type_name,
                bead.name,
                "" if bead.mass is None else f"{float(bead.mass):.8f}",
                f"{float(bead.charge or 0.0):.8f}",
                f"{x:.6f}",
                f"{y:.6f}",
                f"{z:.6f}",
            ])

def render_lammps_input(system: CGSystem, *, data_name: str = "system.data") -> str:
    return (
        "# Generated by Multiscale LAMMPS scaffold.\n"
        "# This input is not parameter-complete. Add pair_style/pair_coeff,\n"
        "# bond_style/bond_coeff and angle_style/angle_coeff before production MD.\n\n"
        "units real\n"
        "atom_style full\n"
        "boundary p p p\n\n"
        f"read_data {data_name}\n\n"
        "# Force-field parameters are intentionally not generated by this topology exporter.\n"
        "# pair_style table linear 1000\n"
        "# pair_coeff * * ...\n"
        "# bond_style table linear 1000\n"
        "# angle_style table linear 1000\n\n"
        "neighbor 2.0 bin\n"
        "neigh_modify delay 0 every 1 check yes\n\n"
        "# Suggested validation command after parameters are supplied:\n"
        "# run 0\n"
    )


def write_lammps_files(system: CGSystem, outdir: str | Path) -> dict[str, Path]:
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    paths = {
        "data": outdir / "system.data",
        "input": outdir / "in.cg",
        "type_map": outdir / "lammps_type_map.json",
        "bead_map": outdir / "lammps_bead_map.csv",
    }
    paths["data"].write_text(render_lammps_data(system), encoding="utf-8")
    paths["input"].write_text(render_lammps_input(system), encoding="utf-8")
    paths["type_map"].write_text(json.dumps(lammps_type_map(system), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_lammps_bead_map_csv(system, paths["bead_map"])
    return paths


def _section_line_count(lines: list[str], section_name: str) -> int:
    active = False
    count = 0
    wanted = section_name.lower()
    headers = {"masses", "atoms", "bonds", "angles"}
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        header = line.split("#", 1)[0].strip().lower()
        if header in headers:
            active = header == wanted
            continue
        if active:
            if line.startswith("#"):
                continue
            if line.split("#", 1)[0].strip().lower() in headers:
                active = False
                continue
            count += 1
    return count


def _section_comment_count(lines: list[str]) -> int:
    active = False
    count = 0
    headers = {"masses", "atoms", "bonds", "angles"}
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        header = line.split("#", 1)[0].strip().lower()
        if header in headers:
            active = True
            continue
        if active:
            if header in headers:
                continue
            if line.startswith("#"):
                count += 1
    return count


def _data_inline_comment_count(lines: list[str]) -> int:
    active = False
    count = 0
    headers = {"masses", "atoms", "bonds", "angles"}
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        header = line.split("#", 1)[0].strip().lower()
        if header in headers:
            active = True
            continue
        if active and "#" in line and not line.startswith("#"):
            count += 1
    return count


def _header_int(lines: list[str], suffix: str) -> int | None:
    for raw in lines:
        line = raw.strip()
        if line.endswith(suffix):
            try:
                return int(line.split()[0])
            except (ValueError, IndexError):
                return None
    return None


def parse_lammps_export_counts(outdir: str | Path) -> dict[str, Any]:
    outdir = Path(outdir)
    data = outdir / "system.data"
    input_file = outdir / "in.cg"
    counts: dict[str, Any] = {
        "has_data": int(data.exists()),
        "has_input": int(input_file.exists()),
        "has_type_map": int((outdir / "lammps_type_map.json").exists()),
        "has_bead_map": int((outdir / "lammps_bead_map.csv").exists()),
        "section_comment_lines": 0,
        "data_inline_comment_lines": 0,
        "ovito_clean_data": False,
        "data_atoms_header": None,
        "data_bonds_header": None,
        "data_angles_header": None,
        "atom_types_header": None,
        "bond_types_header": None,
        "angle_types_header": None,
        "masses": 0,
        "atoms": 0,
        "bonds": 0,
        "angles": 0,
        "input_reads_data": False,
        "no_forcefield_parameters_generated": True,
    }
    if data.exists():
        lines = data.read_text(encoding="utf-8", errors="replace").splitlines()
        counts["data_atoms_header"] = _header_int(lines, "atoms")
        counts["data_bonds_header"] = _header_int(lines, "bonds")
        counts["data_angles_header"] = _header_int(lines, "angles")
        counts["atom_types_header"] = _header_int(lines, "atom types")
        counts["bond_types_header"] = _header_int(lines, "bond types")
        counts["angle_types_header"] = _header_int(lines, "angle types")
        counts["masses"] = _section_line_count(lines, "masses")
        counts["atoms"] = _section_line_count(lines, "atoms")
        counts["bonds"] = _section_line_count(lines, "bonds")
        counts["angles"] = _section_line_count(lines, "angles")
        counts["section_comment_lines"] = _section_comment_count(lines)
        counts["data_inline_comment_lines"] = _data_inline_comment_count(lines)
        counts["ovito_clean_data"] = counts["section_comment_lines"] == 0 and counts["data_inline_comment_lines"] == 0
    if input_file.exists():
        text = input_file.read_text(encoding="utf-8", errors="replace")
        counts["input_reads_data"] = "read_data system.data" in text
        uncommented = [ln.strip() for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
        forbidden = ("pair_coeff", "bond_coeff", "angle_coeff")
        counts["no_forcefield_parameters_generated"] = not any(line.startswith(forbidden) for line in uncommented)
    return counts


def export_lammps_scaffold(system: CGSystem, outdir: str | Path) -> LammpsExportReport:
    paths = write_lammps_files(system, outdir)
    counts = parse_lammps_export_counts(outdir)
    checks: dict[str, bool | None] = {
        "has_data": counts["has_data"] == 1,
        "has_input": counts["has_input"] == 1,
        "has_type_map": counts["has_type_map"] == 1,
        "has_bead_map": counts["has_bead_map"] == 1,
        "ovito_clean_data": bool(counts["ovito_clean_data"]),
        "atoms_match_cgsystem": counts["data_atoms_header"] == len(system.beads) == counts["atoms"],
        "bonds_match_cgsystem": counts["data_bonds_header"] == len(system.bonds) == counts["bonds"],
        "angles_match_cgsystem": counts["data_angles_header"] == len(system.angles) == counts["angles"],
        "atom_types_present": bool(counts["atom_types_header"]),
        "masses_match_atom_types": counts["masses"] == counts["atom_types_header"],
        "input_reads_data": bool(counts["input_reads_data"]),
        "no_forcefield_parameters_generated": bool(counts["no_forcefield_parameters_generated"]),
    }
    return LammpsExportReport(
        outdir=str(Path(outdir)),
        files={key: str(path) for key, path in paths.items()},
        counts=counts,
        checks=checks,
    )
